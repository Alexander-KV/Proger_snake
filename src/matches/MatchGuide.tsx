type Guide = 'rules' | 'docs'

export default function MatchGuide({
  section,
  onBack,
}: {
  section: Guide
  onBack: () => void
}) {
  return (
    <section className="match-guide">
      <h2>{section === 'rules' ? 'Правила игры' : 'Документация'}</h2>
      {section === 'rules' ? (
        <>
          <p>
            На одном клетчатом поле соревнуются змейки команд. Змейками
            управляют алгоритмы, а команды наблюдают за игрой.
          </p>
          <p>
            На каждом тике змейки одновременно делают ход. Еда позволяет змейке
            расти. Столкновения могут привести к выбыванию.
          </p>
          <p>
            Подробные условия победы, столкновений и начисления очков будут
            опубликованы вместе с игровым раундом.
          </p>
        </>
      ) : (
        <>
          <p>
            Организатор выбирает размер поля, вместимость и свою роль. Найдите
            матч в списке и подключитесь, пока есть свободное место.
          </p>
          <p>
            До старта можно читать материалы и покинуть матч. После выхода место
            освобождается для другой команды.
          </p>
          <p>
            Планируемый интерфейс стратегии получает снимок игрового поля и
            возвращает направление движения. Контракт и примеры появятся вместе
            с редактором.
          </p>
        </>
      )}
      <button className="match-button" onClick={onBack}>
        ← В лобби
      </button>
    </section>
  )
}
