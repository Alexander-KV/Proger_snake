type Guide = 'rules' | 'docs'

export default function MatchGuide({
  section,
  onBack,
}: {
  section: Guide
  onBack: () => void
}) {
  return (
    <section className="match-guide">
      <h2>{section === 'rules' ? 'Правила игры' : 'Документация'}</h2>
      {section === 'rules' ? (
        <>
          <p>
            На одном клетчатом поле соревнуются змейки команд. Змейками
            управляют алгоритмы, а команды наблюдают за игрой.
          </p>
          <p>
            На каждом тике змейки одновременно делают ход. Еда позволяет змейке
            расти. Столкновения могут привести к выбыванию.
          </p>
          <p>
            За каждую еду начисляется одно очко. Змейка выбывает при ударе о
            границу, попадании в клетку, занятую телом на начало хода, или
            столкновении голов в одной клетке.
          </p>
          <p>
            Раунд заканчивается, когда остаётся не больше одной змейки, на поле
            кончается место для еды или проходит 300 ходов. Побеждает выжившая
            команда с наибольшим числом очков. Если выбыли все, учитываются очки
            всех команд. При равенстве очков победа общая.
          </p>
        </>
      ) : (
        <>
          <p>
            Организатор выбирает размер поля, вместимость и свою роль. Найдите
            матч в списке и подключитесь, пока есть свободное место.
          </p>
          <p>
            Пока лобби открыто, можно читать материалы и покинуть матч. Когда
            соберутся хотя бы две команды, организатор может начать сразу или
            включить отсчёт. После запуска состав фиксируется.
          </p>
          <p>
            Планируемый интерфейс стратегии получает снимок игрового поля и
            возвращает направление движения. Контракт и примеры появятся вместе
            с редактором.
          </p>
        </>
      )}
      <button className="match-button" onClick={onBack}>
        ← В лобби
      </button>
    </section>
  )
}
