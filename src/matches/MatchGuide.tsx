type Guide = 'rules' | 'docs'

export default function MatchGuide({
  section,
  onBack,
}: {
  section: Guide
  onBack: () => void
}) {
  return (
    <section className="match-guide">
      <h2>{section === 'rules' ? 'Правила игры' : 'Документация'}</h2>
      {section === 'rules' ? (
        <>
          <p>
            На одном клетчатом поле соревнуются змейки команд. Змейками
            управляют алгоритмы, а команды наблюдают за игрой.
          </p>
          <p>
            На каждом ходу змейки двигаются одновременно. Еда добавляет один
            сегмент и одно очко. Столкновение со стеной, телом или встречной
            головой приводит к выбыванию.
          </p>
          <p>
            Раунд длится до 240 ходов. Побеждает последняя выжившая змейка. Если
            остаётся несколько змеек, побеждает набравшая больше очков. Если все
            выбыли на одном ходу, сравниваются очки змеек, выбывших последними.
            При равенстве очков объявляется ничья.
          </p>
        </>
      ) : (
        <>
          <p>
            Организатор выбирает размер поля, вместимость и свою роль. Найдите
            матч в списке и подключитесь, пока есть свободное место.
          </p>
          <p>
            Для старта нужны хотя бы две команды. Организатор может начать сразу
            или с отсчётом. После старта состав фиксируется до конца раунда.
          </p>
          <p>
            Сервер поочерёдно назначает командам две готовые стратегии. «Поиск
            еды» предпочитает короткий путь к еде, а «Свободное поле» учитывает
            доступное пространство и возможные ходы соперников.
          </p>
        </>
      )}
      <button className="match-button" onClick={onBack}>
        ← В лобби
      </button>
    </section>
  )
}
