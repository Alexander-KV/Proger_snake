type Guide = 'rules' | 'docs'

export default function MatchGuide({
  section,
  onBack,
}: {
  section: Guide
  onBack: () => void
}) {
  return (
    <section className="match-guide">
      <h2>{section === 'rules' ? 'Правила игры' : 'Документация'}</h2>
      {section === 'rules' ? (
        <>
          <p>
            На одном клетчатом поле соревнуются змейки команд. Змейками
            управляют алгоритмы, а команды наблюдают за игрой.
          </p>
          <p>
            Все змейки ходят одновременно. Столкновение с границей,
            препятствием, телом или головой змейки смертельно. При общей цели
            или обмене клетками голов погибают обе змейки.
          </p>
          <p>
            Обычная еда прибавляет 10 очков, золотая — 30. Обе увеличивают длину
            на одну клетку. Яд отнимает один сегмент и убивает змейку длиной 2.
            В воде шаг занимает два такта. Щит действует 10 тактов, защищает от
            замедления и поглощает один яд.
          </p>
          <p>
            Единственная выжившая змейка побеждает сразу. По лимиту тактов
            выигрывает выжившая команда с наибольшим счётом. При равенстве
            возможна ничья. Если погибли все, победителя нет.
          </p>
        </>
      ) : (
        <>
          <p>
            Организатор выбирает размер поля, вместимость и свою роль. Найдите
            матч в списке и подключитесь, пока есть свободное место.
          </p>
          <p>
            Организатор задаёт время на написание кода в минутах. Во время
            подготовки откройте редактор и напишите функцию
            <code> decide(state, memory)</code>. В редакторе можно проверить
            код, открыть справку по полям и запустить тестовый матч.
          </p>
          <p>
            Отправьте версию и нажмите «Выбрать для матча». После окончания
            подготовки игра начнётся автоматически. Если выбор не сделан,
            используется самая свежая отправка. Команда без отправки пропускает
            матч.
          </p>
        </>
      )}
      <button className="match-button" onClick={onBack}>
        ← В лобби
      </button>
    </section>
  )
}
